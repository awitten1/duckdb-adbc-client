#!/usr/bin/env bash
# The setup commands as run for this report, in order. Not meant to run unattended: the first half runs on the
# ClickHouse node (hp034, 10.10.1.1), the second on the DuckDB node (hp036, 10.10.1.2). Both nodes start with
# `git clone --recurse-submodules https://github.com/awitten1/duckdb-adbc-client.git` in $HOME, at f0bf5c0.
# Scripts referenced below live in reports/two-node-10gbe-20261111/scripts/.
set -euo pipefail
TWO_NODE=~/duckdb-adbc-client/reports/two-node-10gbe-20261111/scripts

clickhouse_node() {
    # The custom ClickHouse 26.11.1.1 build (commit c933d005d: parallel ArrowStream formatting + direct send),
    # saved on the project's NFS share by the 10 Gb/s run. sha256 330901bdfb870737...
    mkdir -p ~/clickhouse-binaries ~/clickhouse-data ~/duckdb-cli
    cp -p /proj/slogora-PG0/clickhouse-binaries/clickhouse-c933d005d-direct-send ~/clickhouse-binaries/
    cp $TWO_NODE/clickhouse-config-network.xml $TWO_NODE/load_sf50.sh ~/
    sudo systemd-run --unit=adbc-clickhouse --uid=$(id -u) --gid=$(id -g) --working-directory=$HOME/clickhouse-data \
        -p LimitNOFILE=262144 --setenv=TZ=UTC --setenv=HOME=$HOME \
        ~/clickhouse-binaries/clickhouse-c933d005d-direct-send server --config-file=$HOME/clickhouse-config-network.xml
    # TPC-H SF50 generated by the DuckDB 2.0.0 release CLI, then loaded (data/load.txt).
    (cd ~/duckdb-cli && curl -fsSL -o duckdb.tar.gz \
        https://github.com/duckdb/duckdb/releases/download/v2.0.0/duckdb-cli-linux-amd64.tar.gz && tar -xzf duckdb.tar.gz)
    ~/load_sf50.sh
    # Link test server for iperf3 (data/iperf3.txt).
    iperf3 -s -D -B 10.10.1.1 -p 5299 -I /tmp/iperf3.pid
}

duckdb_node() {
    sudo apt-get update -qq
    sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq build-essential cmake ninja-build git python3 curl \
        ca-certificates pkg-config libssl-dev unzip xz-utils util-linux libbenchmark-dev
    cd ~/duckdb-adbc-client
    # The same two patches as every multi-stream report since stream-limits: the read_adbc reader thread
    # (ADBC_READER_THREAD) and DuckDB's faster Arrow string/decimal conversion.
    P=reports/stream-limits-20261110/patches
    git apply $P/adbc-scan-reader-thread-and-timing.patch
    (cd duckdb && git apply ../$P/duckdb-arrow-conversion.patch)
    GEN=ninja CMAKE_BUILD_PARALLEL_LEVEL=20 make release EXT_FLAGS="-DBUILD_EXTENSIONS=tpch -DLINK_CORE_EXTENSIONS=ON"
    ninja -C build/release parallel_read_adbc
    # Rust, then both connector builds (no compression, LZ4) and their ADBC profiles.
    curl --proto "=https" --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --profile minimal
    source ~/.cargo/env
    bash $TWO_NODE/build_connectors.sh
}

both_nodes() {
    # Clocks fixed at the 2.4 GHz base frequency (data/frequency.txt).
    bash $TWO_NODE/pin_frequency.sh
}

case "${1:-}" in
    clickhouse) clickhouse_node ;;
    duckdb) duckdb_node ;;
    clocks) both_nodes ;;
    *) echo "usage: $0 clickhouse|duckdb|clocks" >&2; exit 2 ;;
esac
